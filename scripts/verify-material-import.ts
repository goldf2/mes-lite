import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import ExcelJS from 'exceljs'

async function main() {
  const directory = mkdtempSync(join(tmpdir(), 'mes-material-import-'))
  writeFileSync(join(directory, 'verify.db'), '')
  process.env.DATABASE_URL = `file:${join(directory, 'verify.db')}`
  execFileSync(process.execPath, ['node_modules/prisma/build/index.js', 'db', 'push', '--skip-generate'], { env: process.env, stdio: 'pipe' })
  const { prisma } = await import('../lib/prisma')
  const { previewMaterialImport, importMaterialsCsv, MaterialImportError } = await import('../modules/materials/server/material-import-service')
  const { exportMaterialsCsv } = await import('../modules/materials/server/material-export-service')
  const { parseCsv } = await import('../lib/csv')
  const { materialImportTemplateCsv } = await import('../modules/materials/domain/material-import-fields')
  const { readMaterialImportFile } = await import('../modules/materials/server/material-import-file')
  const { prepareMaterialImportSheet } = await import('../modules/materials/domain/material-mapped-import')
  type Options = import('../modules/materials/contracts/material-import').MaterialImportOptions
  const upload = (text: string, options: Options = {}) => ({ name: 'materials.csv', bytes: new TextEncoder().encode(text), options })
  const actor = { operatorName: '物料导入隔离回归' }
  try {
    const workbook = new ExcelJS.Workbook()
    workbook.addWorksheet('说明').addRow(['请选数据表'])
    const worksheet = workbook.addWorksheet('零件')
    for (let i = 0; i < 5; i += 1) worksheet.addRow([`说明${i}`])
    worksheet.addRow(['配合零件编码','名称','图号','型号','每台数量','长(净)','热处理','基础库存数量','初始成本','热处理工艺','用途'])
    worksheet.addRow(['P-A','123','0123改','A',0,0,false,999,888,'无','自有设备维护;对外加工'])
    worksheet.addRow(['P-B','部件B','B-001','B',null,null,true,999,888,'不用',''])
    const xlsx = { name: 'review.xlsx', bytes: new Uint8Array(await workbook.xlsx.writeBuffer()), options: { worksheet: '零件', headerRow: 6, defaults: { stockUnit: '件', category: 'OTHER', materialKind: 'PART' } } as Options }
    assert.equal((await previewMaterialImport(upload(materialImportTemplateCsv()))).canCommit,true,'注册表模板自身须能通过预览')
    const before = await Promise.all([prisma.material.count(), prisma.stock.count(), prisma.auditLog.count(), prisma.customer.count()])
    const preview = await previewMaterialImport(xlsx)
    assert.equal(preview.canCommit,true)
    assert.equal(preview.summary.new,2)
    assert.equal(preview.worksheets.length,2)
    assert.equal(preview.headerRow,6)
    assert.deepEqual(preview.columns[0].samples,['P-A','P-B'])
    assert.ok(preview.ignoredColumns.some((column) => column.name === '基础库存数量'))
    assert.equal(preview.rows[0].values.finishedLength,0)
    assert.equal(preview.rows[0].values.heatTreatment,false)
    assert.equal(preview.rows[0].name,'123','数字名称本身不是非法值')
    assert.deepEqual(await Promise.all([prisma.material.count(),prisma.stock.count(),prisma.auditLog.count(),prisma.customer.count()]),before,'preview必须无业务或审计写入')
    const summary = await importMaterialsCsv(xlsx,'skip',actor)
    assert.equal(summary.created,2)
    let first = await prisma.material.findUniqueOrThrow({ where:{code:'P-A'}, include:{ stock:true,modelUsages:true,purposes:true } })
    assert.equal(first.stock?.qty,0)
    assert.equal(first.stock?.totalCost,0)
    assert.equal(first.finishedLength,0)
    assert.equal(first.heatTreatment,false)
    assert.equal(first.heatTreatmentProcess,'无')
    assert.equal(first.modelUsages[0].quantityPerMachine,0)
    assert.deepEqual(first.purposes.map((p) => p.purposeCode).sort(),['EXTERNAL_PROCESSING','OWN_EQUIPMENT'])
    assert.equal(await prisma.auditLog.count(),1)
    await prisma.material.update({where:{id:first.id},data:{spec:'原规格',drawingNo:'保留图号',defaultSalePrice:12}})
    await prisma.materialModelUsage.create({data:{materialId:first.id,modelCode:'OTHER',assemblyName:'组2',quantityPerMachine:3}})
    const nameOnly = upload('物料编码,物料名称\nP-A,已更新', {mode:'update'})
    assert.equal((await previewMaterialImport(nameOnly)).canCommit,true)
    await importMaterialsCsv(nameOnly,'update',actor)
    first = await prisma.material.findUniqueOrThrow({where:{code:'P-A'},include:{stock:true,modelUsages:true,purposes:true}})
    assert.equal(first.spec,'原规格','未映射规格必须保留')
    assert.equal(first.drawingNo,'保留图号')
    assert.equal(first.defaultSalePrice,12)
    assert.equal(first.modelUsages.length,2)
    assert.equal(first.purposes.length,2)
    const singleUsage = upload('物料编码,型号,每台数量\nP-A,A,4', {mode:'update'})
    await importMaterialsCsv(singleUsage,'update',actor)
    let usages = await prisma.materialModelUsage.findMany({where:{materialId:first.id}})
    assert.equal(usages.length,2,'单机型导入不得删除其他机型')
    assert.equal(usages.find((u) => u.modelCode==='A')?.quantityPerMachine,4)
    assert.equal(usages.find((u) => u.modelCode==='OTHER')?.quantityPerMachine,3)
    await importMaterialsCsv(upload('物料编码,型号\nP-A,A',{mode:'update'}),'update',actor)
    usages = await prisma.materialModelUsage.findMany({where:{materialId:first.id}})
    assert.equal(usages.find((u) => u.modelCode==='A')?.quantityPerMachine,4,'未映射数量不得清空适用用量')
    const byDrawing = parseCsv(await exportMaterialsCsv({keyword:'保留图号'}))
    assert.equal(byDrawing.length,2,'新增图号搜索结果与导出须保持一致')
    const roundTripCsv = await exportMaterialsCsv({keyword:'P-A'})
    const roundTrip = upload(roundTripCsv,{mode:'update'})
    const roundTripPreview = await previewMaterialImport(roundTrip)
    assert.equal(roundTripPreview.canCommit,true,JSON.stringify(roundTripPreview.rows))
    assert.ok(roundTripPreview.rows[0].warnings.some((message) => message.includes('替换')))
    await importMaterialsCsv(roundTrip,'update',actor)
    usages = await prisma.materialModelUsage.findMany({where:{materialId:first.id}})
    assert.equal(usages.length,2,'导出/再导入必须保留完整多机型关系')
    assert.equal((await prisma.materialPurpose.count({where:{materialId:first.id}})),2)
    const exportedRows = parseCsv(roundTripCsv)
    assert.ok(exportedRows[0].includes('适用机型记录(JSON)'))
    assert.equal((await previewMaterialImport(upload('物料编码,名称,净长\nP-A,,bad'))).summary.skip,1,'skip只需有效编码，不校验可选字段')
    const duplicates = await previewMaterialImport(upload('物料编码,名称,库存单位\nD,一,件\nD,二,件'))
    assert.equal(duplicates.summary.error,2)
    const duplicateHeader = await previewMaterialImport(upload('物料编码,配合零件编码,名称\nX,Y,Z',{defaults:{stockUnit:'件'}}))
    assert.equal(duplicateHeader.mapping.code,null,'多个alias不可猜测')
    await assert.rejects(() => previewMaterialImport(upload('编码,名称\nX,Y',{mapping:{code:0,name:0}})),MaterialImportError)
    assert.throws(() => prepareMaterialImportSheet([['编码','型号','modelUsages'],['X','A','[]']],{}),/不能同时映射/)
    assert.throws(() => prepareMaterialImportSheet([['编码'],['X']],{defaults:{modelUsagesJson:'[]',modelCode:'A'}}),/不能同时映射/)
    await prisma.material.update({where:{id:first.id},data:{defaultSourceMode:'BUY'}})
    await importMaterialsCsv(upload('编码,默认来源\nP-A,',{mode:'update'}),'update',actor)
    assert.equal((await prisma.material.findUniqueOrThrow({where:{id:first.id}})).defaultSourceMode,null,'映射的可空来源字段空白应明确清空')
    const nonFinite = await previewMaterialImport(upload('编码,名称,库存单位,净长\nZ,测试,件,Infinity'))
    assert.equal(nonFinite.canCommit,false)
    const unknownCustomer = await previewMaterialImport(upload('编码,名称,库存单位,归属客户\nZ,测试,件,不存在的客户'))
    assert.equal(unknownCustomer.canCommit,false)
    assert.equal(await prisma.customer.count(),0,'不得悄悄创建客户')
    const mappedBlank = await previewMaterialImport(upload('编码,名称,库存单位\nZ,测试,',{defaults:{stockUnit:'件'}}))
    assert.equal(mappedBlank.canCommit,false,'显式默认值只作用于未映射列，不替换已映射空白')
    await prisma.stock.update({where:{materialId:first.id},data:{qty:5}})
    const locked = await previewMaterialImport(upload('编码,名称,库存单位,主计量方式,核算单位\nP-A,测试,kg,重量,kg',{mode:'update'}))
    assert.equal(locked.canCommit,false)
    assert.ok(locked.rows[0].errors.some((message) => message.includes('计量设置')))
    await prisma.material.update({where:{code:'P-B'},data:{deletedAt:new Date()}})
    assert.equal((await previewMaterialImport(upload('编码\nP-B'))).canCommit,false,'归档占码即便skip也必须阻断')
    const afterPreview = upload('编码,名称,库存单位\nLATE,新建,件')
    assert.equal((await previewMaterialImport(afterPreview)).canCommit,true)
    await prisma.material.create({data:{code:'LATE',name:'并发归档',unit:'件',deletedAt:new Date()}})
    await assert.rejects(() => importMaterialsCsv(afterPreview,'skip',actor),MaterialImportError,'提交须重新读取当前状态')
    const formulaBook = new ExcelJS.Workbook();const formulaSheet=formulaBook.addWorksheet('数据')
    formulaSheet.addRow(['编码','名称','库存单位']);formulaSheet.addRow(['FORMULA',{formula:'"危险"',result:'危险'},'件'])
    const formulaPreview=await previewMaterialImport({name:'formula.xlsx',bytes:new Uint8Array(await formulaBook.xlsx.writeBuffer()),options:{}})
    assert.equal(formulaPreview.canCommit,false,'不信任公式缓存值')
    await assert.rejects(() => readMaterialImportFile(upload('"未闭合')),/引号未闭合/)
    await assert.rejects(() => readMaterialImportFile(upload('\n'.repeat(110000))),/物理行数过多/)
    await assert.rejects(() => readMaterialImportFile({name:'huge.csv',bytes:new Uint8Array(11*1024*1024),options:{}}),/10MB/)
    await prisma.$executeRawUnsafe(`CREATE TRIGGER reject_import_audit BEFORE INSERT ON AuditLog WHEN NEW.action = 'IMPORT_CREATE' BEGIN SELECT RAISE(ABORT, 'audit failure test'); END`)
    await assert.rejects(() => importMaterialsCsv(upload('编码,名称,库存单位\nROLLBACK,回滚,件'),'skip',actor))
    assert.equal(await prisma.material.count({where:{code:'ROLLBACK'}}),0,'审计失败必须回滚物料/空库存创建')
    assert.equal(await prisma.stock.count({where:{material:{code:'ROLLBACK'}}}),0)
    console.log('PASS material import: XLSX/CSV, row6, mapping, read-only preview, partial updates, relation roundtrip, measurement locks, state revalidation, atomic audit rollback')
  } finally {
    await prisma.$disconnect()
    rmSync(directory,{recursive:true,force:true})
  }
}
main().catch((error)=>{console.error(error);process.exitCode=1})
